// Config plugin: restrict the Android APK to phone ABIs.
//
// WHY: a universal APK carries every architecture — arm64-v8a, armeabi-v7a,
// x86 and x86_64. The x86/x86_64 slices exist for emulators and were adding
// tens of megabytes to an APK no real device needs. This keeps the two ARM
// ABIs (arm64 covers every phone since ~2016; armeabi-v7a covers older ones).
//
// Result: the preview APK drops well under the 100 MB target while remaining
// installable on any Android phone. Production ships an AAB, where Play
// already splits per-device, so this only affects the test APK.

const { withAppBuildGradle } = require('@expo/config-plugins');

const MARKER = '// @skillfarm-abi-filters';

module.exports = function withAbiFilters(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      // Kotlin DSL is not generated by Expo today; leave it untouched.
      return cfg;
    }

    let src = cfg.modResults.contents;
    if (src.includes(MARKER)) return cfg;

    const injection = `
    ${MARKER}
    // Phone ABIs only — x86/x86_64 are emulator-only payload.
    defaultConfig {
        ndk {
            abiFilters "arm64-v8a", "armeabi-v7a"
        }
    }
`;

    // Insert as the first child of the `android { ... }` block.
    const anchor = /android\s*\{/;
    if (!anchor.test(src)) {
      console.warn('[withAbiFilters] android block not found — skipping');
      return cfg;
    }
    src = src.replace(anchor, (m) => m + injection);
    cfg.modResults.contents = src;
    return cfg;
  });
};